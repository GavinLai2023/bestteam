//     of a translated string; a comma, a colon or a full stop makes the same
//     break natively.
//   * Quote a name or a button with “”, never 「」 and never ASCII quotes.
//   * Labels are noun phrases. English asks a question for warmth ("What does
//     success look like?"); a Chinese form labels the field and stops.
